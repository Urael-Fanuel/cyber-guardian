const LANGS = {
  en: { name: "English",    flag: "🇺🇸", dir: "ltr" },
  de: { name: "Deutsch",    flag: "🇩🇪", dir: "ltr" },
  ja: { name: "日本語",      flag: "🇯🇵", dir: "ltr" },
  ko: { name: "한국어",      flag: "🇰🇷", dir: "ltr" },
  fr: { name: "Français",   flag: "🇫🇷", dir: "ltr" },
  pt: { name: "Português",  flag: "🇧🇷", dir: "ltr" },
  he: { name: "עברית",       flag: "🇮🇱", dir: "rtl" },
};

function detectLang() {
  const saved = localStorage.getItem('cg-lang');
  if (saved && TRANSLATIONS[saved]) return saved;
  const browser = (navigator.language || 'en').toLowerCase().split('-')[0];
  return TRANSLATIONS[browser] ? browser : 'en';
}

function setLang(code) {
  if (!TRANSLATIONS[code]) return;
  localStorage.setItem('cg-lang', code);
  const t = TRANSLATIONS[code];
  document.documentElement.lang = code;
  document.documentElement.dir = LANGS[code].dir;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key]) el.textContent = t[key];
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (t[key]) el.innerHTML = t[key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (t[key]) el.placeholder = t[key];
  });

  document.querySelectorAll('.lang-btn').forEach(b => {
    b.classList.toggle('active', b.getAttribute('data-lang') === code);
  });
}

window.t = (key) => {
  const code = localStorage.getItem('cg-lang') || detectLang();
  return TRANSLATIONS[code]?.[key] || TRANSLATIONS.en[key] || key;
};
